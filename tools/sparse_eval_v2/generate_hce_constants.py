#!/usr/bin/env python3
"""Extract constants from the authenticated r84 evaluator; never edit v1."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def generated():
    directory = ROOT / "tools/sparse_eval/baseline"
    manifest = json.loads((directory / "manifest.json").read_bytes())
    raw = (directory / "eval.rs").read_bytes()
    expected = next(row["sha256"] for row in manifest["files"] if row["path"] == "eval.rs")
    digest = hashlib.sha256(raw).hexdigest()
    if digest != expected:
        raise ValueError("pinned HCE bytes do not match baseline manifest")
    source = raw.decode()
    constants = source[source.index("const PHASE_MAX"):source.index("#[derive(Clone, Copy)]")]
    constants = re.sub(r"^const ", "pub const ", constants, flags=re.MULTILINE)
    return ("// Generated by generate_hce_constants.py from the pinned r84 eval.rs.\n"
            f"// Source SHA256: {digest}\n"
            "// Constants only; the original baseline source/receipts remain unchanged.\n\n" + constants.rstrip() + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path(__file__).with_name("hce_constants.rs")
    text = generated()
    if args.check:
        if output.read_text() != text:
            raise SystemExit("generated constants differ from authenticated baseline")
    else:
        output.write_text(text)


if __name__ == "__main__":
    main()
