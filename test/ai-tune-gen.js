/*
 * Self-play dataset generator for the evaluation tuner (test/ai-tune.js).
 * Development-only: NOT part of any runtime path and NOT wired into PR CI.
 *
 *   node test/ai-tune-gen.js --games 1600 --nodes 2500 --out tune-data.json
 *   node test/ai-tune-gen.js --games 8 --nodes 300 --workers 1 --out smoke.json
 *
 * Second-generation data pipeline for the experiment PR #63 ran (closed
 * unmerged: "no admissible candidate"). #63's dataset was 600 games of
 * random-6-ply openings played at 700 nodes/move, labelled ONLY by final
 * game outcome — small, noisy, and thin in coverage, which is exactly where
 * its findings located the failure (the one fit that lowered held-out loss
 * was chess-nonsensical and could not mate with K+Q). This generator fixes
 * the data side of that failure:
 *
 *   - REAL OPENINGS: games start from the committed CC0 lichess opening
 *     sample (eval/corpus/sources/openings-v1.tsv) at a seeded truncation
 *     depth, plus a few seeded random plies for spread — sound, diverse
 *     starts instead of random-move chaos. The 41 corpus lines are disjoint
 *     from the 100 frozen match-manifest openings in test/ai-match.js, so
 *     training data never touches the formal-gate manifest (the #105 rule).
 *   - TWO LABELS PER POSITION: the final game outcome AND the White-POV
 *     root search score the engine computed at that position while choosing
 *     its move (free — no extra search). The tuner blends them; a per-
 *     position score target carries far more signal than one outcome bit
 *     shared by every position of a game.
 *   - QUIET-POSITION FILTERS: skip positions in check, positions whose
 *     search PV starts with a capture/promotion (the static eval is never
 *     asked to score those in search — quiescence resolves them), and
 *     positions the search already calls decided (|score| > cp-exclude,
 *     which also excludes mate-band scores). This is the classic Texel
 *     quiet filter #63 lacked.
 *   - SCALE: games are generated by parallel worker processes. Every game
 *     is fully determined by (seed, game index) alone, so the worker count
 *     changes wall-clock time, never content: the merged dataset is
 *     byte-identical for a given config.
 *
 * The output JSON is {config, games, decisive, whiteToMove, samples} where
 * each sample is {b, stm, cp, out, game, ply}: a 64-char board string
 * (a8..h1, '.' empty, uppercase White), side to move, White-POV root search
 * score in centipawns, White-POV game outcome (1 / 0.5 / 0), the game id
 * (the grouped split's key), and the ply. Features are recomputed from `b`
 * by the tuner, so the dataset stays compact and format-stable.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { fork } = require('child_process');
require('../assets/engine.js');
require('../assets/ai.js');
const Chess = globalThis.Chess;
const ChessAI = globalThis.ChessAI;

const SCHEMA = 5; // v2 dataset format (see header); bump on ANY content change

// ---- CLI ----
const args = process.argv.slice(2);
function opt(name, dflt) {
  const i = args.indexOf('--' + name);
  return i >= 0 ? args[i + 1] : dflt;
}
function posInt(name, dflt) {
  const n = Number(opt(name, String(dflt)));
  if (!Number.isSafeInteger(n) || n <= 0) { console.error('--' + name + ' must be a positive integer'); process.exit(2); }
  return n;
}
function nonNegInt(name, dflt) {
  const n = Number(opt(name, String(dflt)));
  if (!Number.isSafeInteger(n) || n < 0) { console.error('--' + name + ' must be a non-negative integer'); process.exit(2); }
  return n;
}

function config() {
  return {
    schema: SCHEMA,
    games: posInt('games', 400),
    nodes: posInt('nodes', 2500),        // per-move search budget during play
    stride: posInt('stride', 2),         // keep 1 of every N eligible plies
    skipPlies: nonNegInt('skip-plies', 4), // plies after book exit before sampling
    maxPlies: posInt('max-plies', 220),  // cap; unfinished games are draws
    bookMin: posInt('book-min', 4),      // minimum opening plies to keep
    randExtra: nonNegInt('rand-extra', 2), // random plies after the book exit
    cpExclude: posInt('cp-exclude', 2000), // drop samples the search calls decided
    seed: posInt('seed', 1)
  };
}

// ---- seeded PRNG (mulberry32, matching the engine's own) ----
function mulberry32(seed) {
  return function () {
    seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---- board codec: 64 chars, index 0..63 = a8..h1, '.' empty, upper = White ----
function encodeBoard(board) {
  let s = '';
  for (let i = 0; i < 64; i++) {
    const p = board[i];
    s += !p ? '.' : (p[0] === 'w' ? p[1] : p[1].toLowerCase());
  }
  return s;
}
function decodeBoard(s) {
  if (typeof s !== 'string' || s.length !== 64) throw new Error('bad board string');
  const board = new Array(64).fill(null);
  for (let i = 0; i < 64; i++) {
    const ch = s[i];
    if (ch === '.') continue;
    const up = ch.toUpperCase();
    if ('PNBRQK'.indexOf(up) < 0) throw new Error('bad board char "' + ch + '"');
    board[i] = (ch === up ? 'w' : 'b') + up;
  }
  return board;
}

// ---- opening book: the committed CC0 lichess sample ----
// Parsed once into SAN token lists and validated by replay; a token that
// fails to match exactly one legal move fails loudly (the corpus is frozen,
// so this only fires if the file or the engine changed).
function loadBook() {
  const tsv = fs.readFileSync(path.join(__dirname, '..', 'eval', 'corpus', 'sources', 'openings-v1.tsv'), 'utf8');
  const lines = tsv.split('\n').filter(function (l) { return l.trim(); });
  const book = [];
  for (let i = 1; i < lines.length; i++) { // skip header
    const cols = lines[i].split('\t');
    if (cols.length < 3) continue;
    const sans = cols[2].split(/\s+/).filter(function (t) {
      return t && !/^\d+\.(\.\.)?$/.test(t) && !/^(1-0|0-1|1\/2-1\/2|\*)$/.test(t);
    });
    if (sans.length >= 2) book.push({ name: cols[1], sans: sans });
  }
  if (book.length < 10) throw new Error('opening book too small (' + book.length + ') — corpus file changed?');
  return book;
}
function stripSan(s) { return s.replace(/[+#]$/, ''); }
function playSan(state, san) {
  const legal = Chess.legalMoves(state);
  const hits = legal.filter(function (x) { return stripSan(Chess.toSan(state, x, legal)) === stripSan(san); });
  if (hits.length !== 1) throw new Error('opening token "' + san + '" matched ' + hits.length + ' moves');
  return Chess.playMove(state, hits[0]);
}

// A capture or promotion at `move` from `state` — the quietness probe for the
// PV's first move. En passant is a pawn's file-changing move to an empty square.
function isCapturePromotion(state, move) {
  if (move.promotion) return true;
  if (state.board[move.to]) return true;
  const p = state.board[move.from];
  return !!(p && p[1] === 'P' && (move.from % 8) !== (move.to % 8));
}

// ---- one self-play game, fully determined by (cfg.seed, g) ----
// Returns null when the seeded opening walk dies (book line or random spread
// reached a finished position) — the caller retries with the next attempt id.
function playOneGame(cfg, g, book) {
  const gameSeed = (cfg.seed * 1000003 + g * 2654435761) >>> 0;
  const rng = mulberry32(gameSeed ^ 0xA5A5A5A5);

  // Opening: seeded book line + truncation depth + random spread plies.
  const line = book[Math.floor(rng() * book.length)];
  const keep = cfg.bookMin + Math.floor(rng() * (line.sans.length - cfg.bookMin + 1));
  let state = Chess.newGameState();
  for (let i = 0; i < keep; i++) {
    if (Chess.gameStatus(state).over) return null;
    state = playSan(state, line.sans[i]);
  }
  for (let i = 0; i < cfg.randExtra; i++) {
    if (Chess.gameStatus(state).over) return null;
    const legal = Chess.legalMoves(state);
    state = Chess.playMove(state, legal[Math.floor(rng() * legal.length)]);
  }
  if (Chess.gameStatus(state).over) return null;
  const bookLen = keep + cfg.randExtra;

  // Per-game sampling phase (the #63 parity fix: without it an even stride
  // over an even book exit would sample only one side to move).
  const phase = Math.floor(rng() * cfg.stride);

  const pending = [];
  let ply = bookLen, status;
  while (ply < cfg.maxPlies && !(status = Chess.gameStatus(state)).over) {
    const r = ChessAI.think(state, {
      maxDepth: 30, nodeLimit: cfg.nodes, quiesce: true,
      seed: (gameSeed + ply) >>> 0, positions: state.positions
    });
    const legal = Chess.legalMoves(state);
    const local = r.move && legal.find(function (m) {
      return m.from === r.move.from && m.to === r.move.to && m.promotion === r.move.promotion;
    });
    if (!local) break;
    // Sample the position the engine just searched (pre-move), using that
    // search's own White-POV root score as the per-position label. Filters:
    // sampling stride, quietness (not in check, PV does not start with a
    // capture/promotion), and not already decided (|cp| beyond cp-exclude —
    // this also excludes the mate band, where cp is MATE minus ply).
    if (ply >= bookLen + cfg.skipPlies &&
        (ply % cfg.stride) === phase &&
        !status.check &&
        Number.isFinite(r.score) &&
        Math.abs(r.score) <= cfg.cpExclude &&
        !isCapturePromotion(state, local)) {
      pending.push({ b: encodeBoard(state.board), stm: state.turn, cp: Math.round(r.score), ply: ply });
    }
    state = Chess.playMove(state, local);
    ply++;
  }

  // Outcome from White's view, exactly as the match harness scores it: the
  // move at the ply cap may itself have ended the game; genuinely unfinished
  // games are draws.
  const fin = Chess.gameStatus(state);
  let out = 0.5;
  if (fin.over && fin.result === '1-0') out = 1;
  else if (fin.over && fin.result === '0-1') out = 0;
  return { samples: pending, out: out, decided: !!(fin.over && (fin.result === '1-0' || fin.result === '0-1')) };
}

// ---- worker mode: generate games g ≡ shard (mod workers), write a shard file ----
function runWorker() {
  const cfg = JSON.parse(process.env.TUNE_GEN_CONFIG);
  const shard = Number(process.env.TUNE_GEN_SHARD);
  const workers = Number(process.env.TUNE_GEN_WORKERS);
  const out = process.env.TUNE_GEN_OUT;
  const book = loadBook();
  const games = [];
  let done = 0;
  for (let g = shard; g < cfg.games; g += workers) {
    // Deterministic retry: attempt ids live in a per-game-slot stream far
    // above the game-id range, so retries can never collide with another slot.
    let rec = null;
    for (let attempt = 0; rec === null && attempt < 50; attempt++) {
      rec = playOneGame(cfg, g + (attempt * 0x40000000 >>> 0), book);
    }
    if (rec === null) continue; // a slot that never yields a game is skipped
    games.push({ g: g, out: rec.out, decided: rec.decided, samples: rec.samples });
    done++;
    if (done % 25 === 0 && process.send) process.send({ progress: done });
  }
  fs.writeFileSync(out, JSON.stringify(games));
  if (process.send) process.send({ done: true, count: games.length });
  process.exit(0);
}

// ---- driver: fork workers, merge shards in game order, write the dataset ----
function runDriver() {
  const cfg = config();
  const OUT = opt('out', null);
  if (!OUT) { console.error('--out <file> is required'); process.exit(2); }
  const WORKERS = posInt('workers', Math.max(1, Math.min(4, require('os').cpus().length)));
  const t0 = Date.now();
  console.log('# ai-tune-gen: ' + cfg.games + ' games @ ' + cfg.nodes + ' nodes/move, stride ' +
    cfg.stride + ', seed ' + cfg.seed + ', ' + WORKERS + ' workers');
  const shardFiles = [];
  let running = 0, progressTotal = 0;
  for (let w = 0; w < WORKERS; w++) {
    const shardFile = OUT + '.shard' + w;
    shardFiles.push(shardFile);
    const child = fork(__filename, [], {
      env: Object.assign({}, process.env, {
        TUNE_GEN_CONFIG: JSON.stringify(cfg),
        TUNE_GEN_SHARD: String(w),
        TUNE_GEN_WORKERS: String(WORKERS),
        TUNE_GEN_OUT: shardFile
      })
    });
    running++;
    child.on('message', function (m) {
      if (m.progress) {
        progressTotal += 25;
        process.stderr.write('\r~' + progressTotal + '/' + cfg.games + ' games, ' +
          Math.round((Date.now() - t0) / 1000) + 's   ');
      }
    });
    child.on('exit', function (code) {
      running--;
      if (code !== 0) { console.error('\nworker exited with code ' + code); process.exit(1); }
      if (running === 0) merge();
    });
  }

  function merge() {
    const all = [];
    for (const f of shardFiles) {
      const shard = JSON.parse(fs.readFileSync(f, 'utf8'));
      for (const rec of shard) all.push(rec);
      fs.unlinkSync(f);
    }
    all.sort(function (a, b) { return a.g - b.g; });
    const samples = [];
    let games = 0, decisive = 0, whiteToMove = 0;
    for (const rec of all) {
      if (rec.samples.length === 0) continue; // unrepresented games stay out of the stats
      games++;
      if (rec.decided) decisive++;
      for (const s of rec.samples) {
        if (s.stm === 'w') whiteToMove++;
        samples.push({ b: s.b, stm: s.stm, cp: s.cp, out: rec.out, game: rec.g, ply: s.ply });
      }
    }
    const data = { config: cfg, games: games, decisive: decisive, whiteToMove: whiteToMove, samples: samples };
    fs.writeFileSync(path.resolve(OUT), JSON.stringify(data));
    const secs = Math.round((Date.now() - t0) / 1000);
    console.log('\nwrote ' + OUT + ': ' + games + ' games (' + decisive + ' decisive, ' +
      (100 * decisive / games).toFixed(1) + '%), ' + samples.length + ' positions (' +
      (100 * whiteToMove / samples.length).toFixed(1) + '% White to move), ' + secs + 's');
  }
}

if (require.main === module) {
  if (process.env.TUNE_GEN_SHARD != null) runWorker();
  else runDriver();
} else {
  module.exports = {
    SCHEMA: SCHEMA, mulberry32: mulberry32,
    encodeBoard: encodeBoard, decodeBoard: decodeBoard,
    loadBook: loadBook, playSan: playSan, isCapturePromotion: isCapturePromotion,
    playOneGame: playOneGame,
    Chess: Chess, ChessAI: ChessAI
  };
}
