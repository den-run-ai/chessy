'use strict';
// Called by pinned reproducibility CI with the three freshly built crates.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const crypto=require('node:crypto');
const {validate}=require('../../tools/search/check-historical-build');
const args=process.argv.slice(2);assert.equal(args.length,3,'provide hash, checks and tactical freshly built crate paths');
const kinds=['hash','checks','tactical'];
function substituted(file,transform,callback){
  const read=fs.readFileSync;
  fs.readFileSync=function(actual,...options){const bytes=read.call(fs,actual,...options);return path.resolve(String(actual))===path.resolve(file)?transform(bytes):bytes;};
  try{return callback();}finally{fs.readFileSync=read;}
}
for(let index=0;index<kinds.length;index++){
  const kind=kinds[index],directory=args[index],report=validate(kind,directory);
  for(const file of report.modules){
    substituted(path.join(directory,file.path),bytes=>Buffer.concat([bytes,Buffer.from([0])]),
      ()=>assert.throws(()=>validate(kind,directory),/historical WASM output changed/));
  }
  for(const file of JSON.parse(fs.readFileSync(path.join(directory,'source.json'))).generated){
    substituted(path.join(directory,file.path),bytes=>Buffer.concat([bytes,Buffer.from('\n// changed\n')]),
      ()=>assert.throws(()=>validate(kind,directory),/generated build input changed/));
  }
  // A matching edit of generated bytes plus their self-reported receipt must
  // still fail against the independently pinned historical inventory.
  const searchPath=path.join(directory,'src/search.rs');
  const changedSearch=Buffer.concat([fs.readFileSync(searchPath),Buffer.from('\n// coherent source edit\n')]);
  const changedHash=crypto.createHash('sha256').update(changedSearch).digest('hex');
  substituted(path.join(directory,'source.json'),bytes=>{
    const receipt=JSON.parse(bytes);
    receipt.generated.find(f=>f.path==='src/search.rs').sha256=changedHash;
    return Buffer.from(JSON.stringify(receipt));
  },()=>substituted(searchPath,()=>changedSearch,
    ()=>assert.throws(()=>validate(kind,directory),/historical generated inventory changed/)));
}
console.log('Historical build oracle rejects all six changed WASM outputs, 24 source inputs and coherent receipt substitutions PASS');
