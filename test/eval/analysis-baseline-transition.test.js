#!/usr/bin/env node
'use strict';

// The compact-hash provider changes identity, not the retained E3 score vector.
// This fixture gate never imports the scorecard or performs a search.
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const pins = {
  'eval/ANALYSIS-BASELINE.json': '20d3a1d1c302886b3dc2a558ed5887435c38af9cab4c0d884e5b4b6f3b8cd8d0',
  'eval/ANALYSIS-BASELINE.md': '5067241a8c66d00769bc8fb80fd07253d9d880c5b66c62009da4aa0ad534fe18',
  'eval/ANALYSIS-BASELINE-v2.0.1.json': '5bd289a2e781102295960a475478ea3e87ab3fe3115f308377f51a85ff6640b9',
  'eval/ANALYSIS-FULL-BASELINE.json': '5f4b4675220f449256cce6d489f2d769796ac66c86c5ed3b31b380aa18ce7e98',
  'eval/ANALYSIS-FULL-BASELINE-v2.0.1.json': 'd1f25be76f8fd9bb0441c03d84444ffcfa9306d28b54c2df4d3a8b71e740eabd'
};
function authenticate(file, bytes) {
  assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), pins[file],
    'retained fixture bytes changed: ' + file);
}
function transition(before, after) {
  assert.equal(before.analysis_engine.version, '2.0.0');
  assert.equal(after.analysis_engine.version, '2.0.1');
  const expected = JSON.parse(JSON.stringify(before));
  expected.analysis_engine.version = '2.0.1';
  if (before.mode === 'full') {
    // The unchanged CLI does not emit the old archival annotations. Their
    // exact historical values stay in the old file, never on a new result.
    assert.equal(before.baseline_release, 'r73');
    assert.equal(before.baseline_commit, '07b29d39c07761bd9e1cec242ac16e0435e15f7a');
    for (const field of ['baseline_release', 'baseline_commit']) {
      assert.equal(Object.hasOwn(after, field), false);
      delete expected[field];
    }
  }
  assert.deepEqual(after, expected, 'only provider version and declared archival metadata may differ');
}
const captured = Object.fromEntries(Object.keys(pins).map(file => {
  const bytes = fs.readFileSync(path.join(root, file));
  authenticate(file, bytes);
  return [file, bytes];
}));
let checks = 0;
function reject(before, after, label, mutate) {
  const changed = JSON.parse(JSON.stringify(after));
  mutate(changed);
  assert.throws(() => transition(before, changed), { name: 'AssertionError' }, label);
  checks++;
}
for (const file of Object.keys(pins)) {
  assert.throws(() => authenticate(file, Buffer.concat([captured[file], Buffer.from(' ')])),
    /retained fixture bytes changed/, 'old history and exact generated bytes stay immutable');
  checks++;
}
const mutations = [
  ['wrong provider version', v => { v.analysis_engine.version = '2.0.2'; }],
  ['different engine', v => { v.analysis_engine.id = 'another-engine'; }],
  ['different provider', v => { v.analysis_engine.provider = 'another-provider'; }],
  ['changed corpus', v => { v.ndjson_sha256 = '0'.repeat(64); }],
  ['changed mode', v => { v.mode = v.mode === 'full' ? 'shard' : 'full'; }],
  ['smaller case inventory', v => { v.cases--; }],
  ['changed node budget', v => { v.e3_opts.ref.nodeLimit++; }],
  ['changed candidate width', v => { v.e3_opts.ship.multiPV--; }],
  ['changed criterion version', v => { v.criterion.version++; }],
  ['changed accepted-move tolerance', v => { v.criterion.params.cpTolerance++; }],
  ['lost strict coverage', v => { v.axes.rootComplete.checked--; }],
  ['new strict failure', v => { v.axes.playedRank.fail++; }],
  ['quality regression', v => { v.axes.puzzleTop1.pass--; }],
  ['quality improvement is still a changed fixture', v => { v.axes.puzzleTop1.pass++; }],
  ['smaller regret sample', v => { v.regret.n--; }],
  ['changed regret tail', v => { v.regret.p90++; }],
  ['missing equivalence case', v => { v.axes.equivalence.cases.pop(); }],
  ['changed verdict at equal coverage', v => { v.axes.equivalence.cases[0].verdict = 'unknown'; }],
  ['changed reason at equal coverage', v => { v.axes.equivalence.cases[0].reason = 'not-covered'; }],
  ['changed rank diagnostic', v => { v.axes.equivalence.cases[0].rankLowerBound++; }],
  ['changed covered roots', v => { v.axes.equivalence.cases[0].coveredRootCount--; }],
  ['missing field', v => { delete v.totals.strictFail; }],
  ['added field', v => { v.unreviewed = true; }],
  ['changed gate', v => { v.gate = 'FAIL'; }]
];
for (const stem of ['ANALYSIS-BASELINE', 'ANALYSIS-FULL-BASELINE']) {
  const before = JSON.parse(captured['eval/' + stem + '.json']);
  const after = JSON.parse(captured['eval/' + stem + '-v2.0.1.json']);
  transition(before, after);
  checks++;
  for (const [label, mutate] of mutations) reject(before, after, stem + ': ' + label, mutate);
  if (before.mode === 'full') {
    reject(before, after, 'missing full regret p99', v => { delete v.regret.p99; });
    reject(before, after, 'changed full regret p99', v => { v.regret.p99++; });
    for (const field of ['baseline_release', 'baseline_commit']) {
      reject(before, after, 'old annotation cannot label new output', v => { v[field] = before[field]; });
      const changed = JSON.parse(JSON.stringify(before));
      changed[field] = 'changed';
      assert.throws(() => transition(changed, after), { name: 'AssertionError' },
        'the exact old archival annotation must be retained');
      checks++;
    }
  }
}
console.log(checks + ' E3 fixture-transition checks passed; shard/full measurements preserved, no search executed');
